import type { Acta } from "../client";
import type {
  AuditReport,
  Decision,
  ExtractedInvoice,
  InvoiceSource,
  ISODate,
  ISODateTime,
  LedgerEntry,
  Metrics,
  PaymentExecution,
  Policy,
} from "../contracts";
import raw from "./demo-dataset.json";

/** One invoice of the prototype week, already decided by the prototype engine. */
export interface DemoItem {
  decision: Decision;
  received_at: ISODateTime;
  source: InvoiceSource;
  extraction: ExtractedInvoice;
  expected: "pay" | "hold" | "escalate" | null;
}

export interface DemoCompany {
  name: string;
  today: ISODate;
  base_currency: string;
  opening_balance: number;
  balance_end: number;
  spent_auto_base: number;
}

export interface DemoDataset {
  company: DemoCompany;
  policy: Policy;
  metrics: Metrics;
  audit: AuditReport;
  items: DemoItem[];
  ledger: LedgerEntry[];
}

/** Generated by scripts/port-prototype-dataset.mjs; the cast is the JSON boundary. */
export const DEMO = raw as DemoDataset;

const PAID: ReadonlySet<Decision["status"]> = new Set(["paid_auto", "paid_human"]);

/** The mock has no rail: whatever it pays is simulated, and the acta says so. */
export function simulatedExecution(at: string): PaymentExecution {
  return { rail: "simulated", status: "simulated", external_id: null, dashboard_url: null, executed_at: at, error: null };
}

export function freshDemo(): DemoDataset {
  const demo = structuredClone(DEMO);
  for (const item of demo.items) {
    if (PAID.has(item.decision.status)) item.decision.execution ??= simulatedExecution(item.received_at);
  }
  return demo;
}

/** The acta the API serves for a decided invoice: the decision, the invoice as read and its ledger entries. */
export function actaOf({ decision, received_at, extraction }: DemoItem, ledger: readonly LedgerEntry[]): Acta {
  const id = decision.invoice_id;
  return {
    decision,
    invoice: { id, received_at, document_id: null, status: "decided", read_ok: true, extraction },
    ledger: ledger.filter((entry) => entry.subject_id === id),
  };
}
