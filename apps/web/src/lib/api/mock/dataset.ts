import type { DecisionDetail } from "../client";
import type { AuditReport, Decision, LedgerEntry, Metrics, PaymentExecution, Policy } from "../contracts";
import raw from "./demo-dataset.json";

export interface DemoItem extends DecisionDetail {
  expected: "pay" | "hold" | "escalate" | null;
}

export interface DemoDataset {
  company: {
    name: string;
    place: string;
    today: string;
    base_currency: string;
    opening_balance: number;
    balance_end: number;
    spent_auto_base: number;
    fx_units_per_base: Record<string, number>;
  };
  policy: Policy;
  metrics: Metrics;
  audit: AuditReport;
  items: DemoItem[];
  ledger: LedgerEntry[];
}

/** Generated by scripts/port-prototype-dataset.mjs; the cast is the JSON boundary. */
export const DEMO = raw as DemoDataset;

const PAID: ReadonlySet<Decision["status"]> = new Set(["paid_auto", "paid_human"]);

/** The mock has no rail: whatever it pays is simulated, and the acta says so. */
export function simulatedExecution(at: string): PaymentExecution {
  return { rail: "simulated", status: "simulated", external_id: null, dashboard_url: null, executed_at: at, error: null };
}

export function freshDemo(): DemoDataset {
  const demo = structuredClone(DEMO);
  for (const item of demo.items) {
    if (PAID.has(item.decision.status)) item.decision.execution ??= simulatedExecution(item.received_at);
  }
  return demo;
}
