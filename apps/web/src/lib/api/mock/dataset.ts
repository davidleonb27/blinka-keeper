import type { DecisionDetail } from "../client";
import type { AuditReport, LedgerEntry, Metrics, Policy } from "../contracts";
import raw from "./demo-dataset.json";

export interface DemoItem extends DecisionDetail {
  expected: "pay" | "hold" | "escalate" | null;
}

export interface DemoDataset {
  company: {
    name: string;
    place: string;
    today: string;
    base_currency: string;
    opening_balance: number;
    balance_end: number;
    spent_auto_base: number;
    fx_units_per_base: Record<string, number>;
  };
  policy: Policy;
  metrics: Metrics;
  audit: AuditReport;
  items: DemoItem[];
  ledger: LedgerEntry[];
}

/** Generated by scripts/port-prototype-dataset.mjs; the cast is the JSON boundary. */
export const DEMO = raw as DemoDataset;

export function freshDemo(): DemoDataset {
  return structuredClone(DEMO);
}
